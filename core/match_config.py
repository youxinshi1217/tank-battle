"""
双人模式（PVP）统一对局配置表（纯逻辑层，不依赖 pygame）。

职责：PVP 系列赛参数集中于此，杜绝魔法数字散落 Game 层。
  - 可选对局数 N（5/7/9/11/13）
  - 胜局数 W = ceil(N/2)（先赢 ⌈N/2⌉ 局者胜全部）
"""

# PVP 可选对局数（均为奇数，胜局 = ⌈N/2⌉；由玩家在双人模式页选择）
PVP_ROUNDS_CHOICES = (5, 7, 9, 11, 13)


def get_win_rounds_from_n(n: int) -> int:
    """由局数 N 推导胜局数 = ceil(N/2)（奇数 N 时 = (N+1)//2）。

    供 PVP 对局数选择使用：5→3、7→4、9→5、11→6、13→7。
    """
    return (n + 1) // 2